/// The maximum time a single ticket registration is allowed to take before the
/// ticket controller surfaces a failure (Requirements 3.8, 3.9).
const Duration ticketTimeout = Duration(seconds: 10);

/// Gate / pluma identifier used when building a [TicketRequest] and generating
/// the ticket `qrCode`.
///
/// ASSUMPTION: The current scope has no gate/pluma picker UI, so a single
/// default pluma is used. The `qrCode` is generated from the session's
/// `parkingLotKeyCode` and this pluma via [QrCodeGenerator]. Replace with a
/// real gate selection once the corresponding UI is added.
const String kDefaultPlumaId = '1';

/// Provides the [TicketService] used to register tickets against the
/// Ticket_Register_Endpoint.
///
/// Defaults to a [HttpTicketService] built from [httpClientProvider] (reused
/// from `login_controller.dart`) and [appConfigProvider]. It can be overridden
/// in tests via `ProviderScope` `overrides`, e.g.:
/// ```dart
/// ProviderScope(
///   overrides: [
///     ticketServiceProvider.overrideWithValue(FakeTicketService()),
///   ],
///   child: const MyApp(),
/// );
/// ```
final ticketServiceProvider = Provider<TicketService>((ref) {
  final client = ref.watch(httpClientProvider);
  final config = ref.watch(appConfigProvider);
  return HttpTicketService(client: client, config: config);
});

/// Orchestrates the Main_Screen ticket registration flow, exposing an immutable
/// [TicketActionState] that starts at [TicketIdle].
///
/// See design.md — the controller builds a [TicketRequest] from the current
/// [Session] (using `parkingLotId` from `session.user`), calls
/// [TicketService.register] with the session `Operator_Token` under a
/// 10-second budget, transitions `TicketIdle → TicketRegistering →
/// TicketConfirmed/TicketFailed`, treats the action as confirmed only when
/// [TicketResult.isConfirmed], and never records confirmation on
/// failure/timeout/unavailability (Requirements 3.3, 3.4, 3.5, 3.8, 3.9).
final ticketControllerProvider =
    StateNotifierProvider<TicketController, TicketActionState>((ref) {
  return TicketController(ref);
});

/// [StateNotifier] backing the [ticketControllerProvider].
class TicketController extends StateNotifier<TicketActionState> {
  final Ref _ref;

  TicketController(this._ref) : super(const TicketIdle());

  /// Registers a ticket of the given [type].
  ///
  /// Flow:
  /// 1. Reads the current [Session] from [sessionProvider]. If no session
  ///    exists (unauthenticated), sets [TicketFailed] and returns without
  ///    calling the service (guard for Requirement 3.6/3.8).
  /// 2. Builds a [TicketRequest] using `parkingLotId` from `session.user` and a
  ///    `qrCode` generated by [QrCodeGenerator] from the session's
  ///    `parkingLotKeyCode` and [kDefaultPlumaId], and sets
  ///    `applyPromotion: true` when [type] is [TicketType.promotion]
  ///    (Requirements 3.3, 3.4).
  /// 3. Transitions to [TicketRegistering], disabling both buttons
  ///    (Requirement 3.9).
  /// 4. Calls [TicketService.register] with the session token under a
  ///    10-second budget (Requirement 3.8).
  /// 5. On result, sets [TicketConfirmed] when [TicketResult.isConfirmed],
  ///    otherwise [TicketFailed] (Requirements 3.5, 3.8).
  /// 6. On [TicketUnavailableException], timeout, or any other error, sets
  ///    [TicketFailed] and records no confirmation (Requirement 3.8).
  Future<void> register(TicketType type) async {
    // 1. Guard: an authenticated session is required to register a ticket.
    final session = _ref.read(sessionProvider);
    if (session == null || !session.isAuthenticated) {
      state = TicketFailed(type: type);
      return;
    }

    // 2. Build the request body for the Ticket_Register_Endpoint. The qrCode is
    //    generated from the session's parkingLotKeyCode and the default pluma
    //    following the ticket QR format (see QrCodeGenerator).
    final qrCode = QrCodeGenerator.generate(
      parkingLotKeyCode: session.user.parkingLotKeyCode,
      plumaId: kDefaultPlumaId,
    );
    final request = TicketRequest(
      parkingLotId: session.user.parkingLotId,
      qrCode: qrCode,
      napUserId: session.user.id,
      applyPromotion: type == TicketType.promotion,
    );

    // 3. Disable both buttons while registering.
    state = const TicketRegistering();

    final service = _ref.read(ticketServiceProvider);
    try {
      // 4. Register under a 10-second budget.
      final result = await service
          .register(request, operatorToken: session.token)
          .timeout(ticketTimeout);

      // 5. Confirmed only when both checkin and checkout succeeded. Carry the
      //    qrCode sent to the service so the confirmed ticket can be printed.
      if (result.isConfirmed) {
        state = TicketConfirmed(type: type, qrCode: qrCode);
      } else {
        state = TicketFailed(
          type: type,
          errorDetail: 'Respuesta del servidor: ticket no confirmado',
        );
      }
    } on TicketUnauthorizedException {
      // 6a. The Operator_Token is no longer valid: erase the stored login data.
      //     Clearing the session drives the router's guard to redirect to the
      //     Login_Screen (Requirement 3.11).
      _ref.read(sessionProvider.notifier).state = null;
      state = TicketFailed(
        type: type,
        errorDetail: 'TicketUnauthorizedException: token inválido (401/403)',
      );
    } on TicketUnavailableException {
      // 6b. Backend_API unavailable / non-2xx / malformed response.
      state = TicketFailed(
        type: type,
        errorDetail: 'TicketUnavailableException: servicio no disponible',
      );
    } on TimeoutException {
      // 6c. Exceeded the 10-second budget.
      state = TicketFailed(
        type: type,
        errorDetail: 'TimeoutException: se excedió el tiempo de espera (10s)',
      );
    } catch (e) {
      // 6d. Any other unexpected failure — never record confirmation.
      state = TicketFailed(
        type: type,
        errorDetail: 'Error inesperado: $e',
      );
    }
  }

  /// Resets the controller to its initial [TicketIdle] state.
  void reset() {
    state = const TicketIdle();
  }
}

/// Holds the current device system theme [DevicePreference].
///
/// Defaults to [DevicePreference.unspecified] (which resolves to a dark scheme
/// per Requirement 4.5). The app layer updates this when the OS theme
/// preference changes at runtime (Requirement 4.6), e.g. from
/// `MediaQuery.platformBrightnessOf(context)`:
/// ```dart
/// ref.read(devicePreferenceProvider.notifier).state =
///     platformBrightness == Brightness.dark
///         ? DevicePreference.dark
///         : DevicePreference.light;
/// ```
final devicePreferenceProvider = StateProvider<DevicePreference>(
  (ref) => DevicePreference.unspecified,
);

/// Exposes the resolved [Brightness] for the current [devicePreferenceProvider],
/// mapped via [ThemeResolver.resolve] (Requirements 4.2–4.5).
///
/// Because it watches [devicePreferenceProvider], the value updates reactively
/// whenever the device theme preference changes at runtime, letting the app
/// rebuild with the matching Material 3 scheme (Requirement 4.6).
final themeModeProvider = Provider<Brightness>((ref) {
  final preference = ref.watch(devicePreferenceProvider);
  return ThemeResolver.resolve(preference);
});
